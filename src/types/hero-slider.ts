/**
 * Типы данных рекламного блока главной страницы (Hero Slider + баннеры).
 *
 * Структуры соответствуют данным, которые на этапе интеграции
 * будет передавать 1С-Битрикс из инфоблоков.
 */

/** Слайд основного Hero Slider */
export interface HeroSlideData {
  /** Заголовок слайда */
  name: string;
  /**
   * HTML-описание. Допустимые теги: p, ul, li, br, span, strong, em.
   * При передаче из CMS HTML должен очищаться на сервере.
   */
  text: string;
  /** URL перехода (заголовок и кнопка). Без URL слайд остаётся некликабельным */
  link?: string;
  /**
   * Фоновое изображение. Написание поля `backgraund` сохранено
   * для совместимости с существующими данными.
   */
  backgraund: string;
  /** Отдельное товарное изображение (справа на desktop) */
  img?: string;
  /** Произвольный overlay поверх фона (CSS background), переопределяет стандартный */
  overlay?: string;
}

/** Рекламный баннер (assets/slider-banners.json) */
export interface HeroBannerData {
  /** Заголовок баннера */
  name: string;
  /** Описание, допускается ограниченная HTML-разметка (например, <br>) */
  text?: string;
  /** Путь к изображению (относительно корня сайта) */
  img: string;
  /** URL страницы. Без URL баннер выводится некликабельным элементом */
  link?: string;
}

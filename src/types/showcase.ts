/**
 * Тип данных витрины категорий каталога.
 *
 * Соответствие будущим данным 1С-Битрикс:
 * - name — название раздела инфоблока каталога;
 * - img  — путь к изображению раздела;
 * - url  — URL раздела (может отсутствовать).
 * Порядок элементов массива = порядок сортировки разделов.
 */
export interface ShowcaseItem {
  /** Название категории (выводится полностью, без сокращений) */
  name: string;
  /** Путь к изображению (относительно корня сайта) */
  img: string;
  /**
   * URL раздела. Пустая строка или отсутствие — карточка некликабельная.
   * Реальные URL будут передаваться из CMS.
   */
  url?: string;
}
